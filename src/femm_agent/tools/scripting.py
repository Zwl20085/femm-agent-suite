"""Scripting tools: generic validated command passthrough, one-line eval, multi-line scripts
(in-process or batch), legacy Lua 4 scripts, the call journal and export to a pyFEMM script."""
from __future__ import annotations

import ast
import os
import re
import subprocess
import time
from pathlib import Path
from typing import Any

from .. import catalog, ipc
from ..sessions import PHYSICS_BY_CODE, PHYSICS_BY_EXT, Session
from ._common import ToolContext, ToolInputError, as_list, envelope, jsonable, run_tool

_SOL_EXT = {".ans": "magnetics", ".res": "electrostatics", ".anh": "heatflow", ".anc": "currentflow"}
_PRE_PHYS = {"mi": "magnetics", "ei": "electrostatics", "hi": "heatflow", "ci": "currentflow"}
_INTERNAL = re.compile(r"^(1\+1|setcurrentdirectory\(.*\)|quit\(\)|globals\(\)\.(pop|get)\(.*\))$")


def track_state(s: Session, line: str) -> None:
    """Keep the session's physics/solved flags right after raw calls (femm_call/eval/scripts)."""
    for m in re.finditer(r"newdocument\(\s*(\d)", line):
        s.physics, s.document, s.solved = PHYSICS_BY_CODE.get(int(m.group(1)), s.physics), None, False
        s.notes.pop("axi", None)
    for m in re.finditer(r"(?:opendocument|open)\(\s*[\"']([^\"']+)[\"']", line):
        ext = Path(m.group(1)).suffix.lower()
        if ext in PHYSICS_BY_EXT:
            s.physics, s.document, s.solved = PHYSICS_BY_EXT[ext], m.group(1), False
            s.notes.pop("axi", None)
        elif ext in _SOL_EXT:
            s.physics, s.solved = _SOL_EXT[ext], True
    for m in re.finditer(r"\b([mehc]i)_loadsolution\(", line):
        s.physics = _PRE_PHYS[m.group(1)]
        s.solved = True
    for m in re.finditer(r"\b([mehc]i)_saveas\(\s*[\"']([^\"']+)[\"']", line):
        s.document = m.group(2)
    if re.search(r"\b[mehc]i_probdef\(", line):
        s.notes.pop("axi", None)


def literal(v: Any) -> Any:
    """FEMM replies with the repr of lists/tuples/dicts as one string; turn those back into data."""
    if isinstance(v, str) and v[:1] in "[({'\"" and v[-1:] in "])}'\"":
        try:
            return ast.literal_eval(v)
        except Exception:
            return v
    return v


def _scripts_dir(s: Session) -> Path:
    d = s.work_dir / "scripts"
    d.mkdir(parents=True, exist_ok=True)
    return d


def journal_to_pyfemm(lines: list[str], headless: bool = True, femm_dir: str | None = None) -> str:
    """Turn raw wire lines into a standalone pyFEMM script. pyFEMM finds the engine only through
    FEMM_DIR (verified), so the detected bin folder is set as a default."""
    out = ["# Generated by FEMM Agent Suite (femm_export_pyfemm_script) from the session journal.",
           "# Re-run with the pyFEMM that ships with FEMM 5:  python this_file.py",
           "# (pyfemm lives in <FEMM install>/pyfemm; add it to PYTHONPATH or pip install it.)",
           "import os",
           f"os.environ.setdefault('FEMM_DIR', {femm_dir!r})  # pyFEMM needs this to find femm_headless"
           if femm_dir else "# set FEMM_DIR to the FEMM 5 bin folder if pyFEMM cannot find the engine",
           "import femm",
           "from femm import *  # lets exec()'d in-process scripts run unchanged", "",
           f"femm.openfemm({1 if headless else 0})"]
    call = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)\((.*)\)$")
    for ln in lines:
        t = ln.strip()
        if _INTERNAL.match(t):
            continue
        if t.startswith("#!"):
            out.append("# refused by FEMM, skipped: " + t[2:].strip())
            continue
        m = call.match(t)
        if m and m.group(1) == "exec":
            out.append(t + "  # in-process script run by femm_run_script")
        elif m:
            out.append(f"femm.{m.group(1)}({m.group(2)})")
        else:
            out.append(f"# not a plain call (femm_eval expression), kept as a comment: {t}")
    out += ["", "femm.closefemm()", ""]
    return "\n".join(out)


def register(mcp, ctx: ToolContext) -> None:
    @mcp.tool()
    def femm_call(command: str, args: list[Any] | None = None, session: str = "main") -> dict:
        """Call any FEMM 5 scripting command by name with positional `args`, e.g.
        femm_call('mi_makeABC', [7, 50, 0, 0, 0]) or femm_call('mo_getgapb', ['AGE', 15]).
        The call is checked against the command catalog first; warnings (wrong arity or types,
        unknown name, pyFEMM-only helpers such as mo_getb that the engine lacks) are returned in
        `warnings`, and the call is still sent unless the name is unknown to both the catalog and
        the engine. Strings are quoted for you; complex values: [re, im] is NOT converted here,
        pass a string expression via femm_eval instead. Use femm_api_search to find commands."""
        def run(s: Session):
            a = as_list(args)
            warnings = catalog.validate_args(command, a)
            entry = catalog.get(command)
            ro = catalog.is_read_only(command)
            try:
                v = s.call(command, *a)
            except ipc.FemmError as e:
                if warnings:
                    raise ToolInputError(f"{e.message} (command: {e.command})",
                                         "Catalog warnings: " + " | ".join(warnings)) from e
                raise
            track_state(s, ipc.build_command(command, a))
            out: dict[str, Any] = {"command": ipc.build_command(command, a)[:300], "value": jsonable(v)}
            if warnings:
                out["warnings"] = warnings
            if entry is not None:
                out["returns"] = entry.get("returns")
                out["read_only"] = ro
            return out
        return run_tool(ctx, session, run)

    @mcp.tool()
    def femm_eval(expression: str, session: str = "main") -> dict:
        """Evaluate ONE LINE of MicroPython inside FEMM and return its value (tab-separated reply
        parsed to numbers/lists). Statements return null; expressions return their value. A
        newline is rejected: for multi-line code use femm_run_script. Examples:
        'mo_getpointvalues(0,0)[1]', 'mi_getboundingbox()', '[mo_getgapb("AGE",a)[0] for a in range(0,90,10)]'.
        Variables persist between calls in the same session."""
        def run(s: Session):
            if "\n" in expression or "\r" in expression:
                raise ToolInputError("expression must be a single line", "Use femm_run_script(code=...) for multi-line code.")
            v = s.link.eval(expression)
            track_state(s, expression)
            return {"value": jsonable(literal(v))}
        return run_tool(ctx, session, run)

    @mcp.tool()
    def femm_run_script(code: str | None = None, path: str | None = None, mode: str = "inprocess",
                        result_var: str = "result", args: list[str] | None = None, timeout: float = 600.0,
                        session: str = "main") -> dict:
        """Run a multi-line MicroPython script with FEMM's commands as globals (mi_addnode(...) etc.,
        no `femm.` prefix). Give `code` or `path` (.py).
        mode=inprocess (default): written to <work_dir>/scripts and executed inside this session's
          engine with exec(open(p).read()) (VERIFIED on FEMM 5): it sees and changes the session's
          model; set a global `result` (or `result_var`) to return a value; print() output is NOT
          captured (the engine's stdout is discarded).
        mode=batch: runs `femm_headless --port <free> -run script.py args...` as a separate engine
          (fresh state, exits at the end); returns stdout, stderr and exit code (1 on a script
          error, with the message in stderr). Use for long independent jobs or sys.argv-driven scripts."""
        def run_inprocess(s: Session):
            if path:
                p = Path(path)
                if not p.is_absolute():
                    p = s.work_dir / p
                if not p.is_file():
                    raise ToolInputError(f"script not found: {p}", "Pass an existing .py path or code=...")
                text = p.read_text(encoding="utf-8", errors="replace")
            elif code:
                text = code
                p = _scripts_dir(s) / f"script_{int(time.time() * 1000)}.py"
                p.write_text(code, encoding="utf-8")
            else:
                raise ToolInputError("give code or path", "Pass code='...' or path='script.py'.")
            if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", result_var):
                raise ToolInputError("result_var must be an identifier", "Use e.g. result_var='result'.")
            t0 = time.time()
            # clear a stale result first so we don't report the previous script's value
            s.link.eval(f"globals().pop({result_var!r}, None)")
            s.link.eval(f"exec(open({ipc.encode_arg(p.resolve().as_posix())}).read())", timeout=timeout)
            track_state(s, text)
            val = s.link.eval(f"globals().get({result_var!r})")
            return {"script": p.resolve().as_posix(), "mode": "inprocess", "seconds": round(time.time() - t0, 3),
                    result_var: jsonable(literal(val))}

        if mode == "inprocess":
            return run_tool(ctx, session, run_inprocess)

        def run_batch():
            inst = ctx.sessions.install
            if inst is None:
                raise ipc.FemmLinkError("FEMM 5 not found. Install it or set FEMM_DIR.")
            wd = ctx.sessions.default_work_dir / "batch"
            wd.mkdir(parents=True, exist_ok=True)
            if path:
                p = Path(path).resolve()
                if not p.is_file():
                    raise ToolInputError(f"script not found: {p}", "Pass an existing .py path.")
            elif code:
                p = wd / f"batch_{int(time.time() * 1000)}.py"
                p.write_text(code, encoding="utf-8")
            else:
                raise ToolInputError("give code or path", "Pass code='...' or path='script.py'.")
            exe = inst.bin_dir / ("femm_headless.exe" if os.name == "nt" else "femm_headless")
            if not exe.is_file():
                exe = inst.headless
            port = ipc.pick_free_port(ipc.DEFAULT_PORT + 50)
            cmd = [str(exe), "--port", str(port), "-run", str(p)] + [str(a) for a in as_list(args)]
            t0 = time.time()
            kw: dict[str, Any] = {}
            if os.name == "nt":
                kw["creationflags"] = getattr(subprocess, "CREATE_NO_WINDOW", 0)
            try:
                r = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, cwd=str(p.parent), **kw)
            except subprocess.TimeoutExpired as e:
                raise ToolInputError(f"batch script exceeded {timeout} s", "Increase timeout or split the job.") from e
            err_lines = [ln for ln in (r.stderr or "").splitlines()
                         if not ln.startswith(("FEMM headless engine", "IPC: listening", "Executing:", "Script complete"))]
            return {"script": p.as_posix(), "mode": "batch", "exit_code": r.returncode, "ok_script": r.returncode == 0,
                    "stdout": (r.stdout or "")[-20000:], "stderr": "\n".join(err_lines)[-5000:],
                    "seconds": round(time.time() - t0, 3), "cwd": p.parent.as_posix()}

        if mode == "batch":
            return envelope(run_batch)
        def bad_mode():
            raise ToolInputError(f"unknown mode {mode!r}", "Use mode='inprocess' or mode='batch'.")
        return envelope(bad_mode)

    @mcp.tool()
    def femm_run_lua(path: str, args: list[str] | None = None, headless: bool = True, timeout: float = 600.0) -> dict:
        """Run a legacy FEMM 4.2 Lua script unchanged with FEMM 5's bundled Lua 4 interpreter
        (bin/femm-lua.bat on Windows: `femm-lua -h -p <free port> script.lua args`). It spawns its
        own engine (not a session) and exits when done. VERIFIED on Windows with a small
        newdocument/mi_probdef/mi_addnode/print script. Returns stdout/stderr/exit code. To port a
        Lua script permanently, rewrite it with femm_run_script (MicroPython) instead."""
        def run():
            inst = ctx.sessions.install
            if inst is None:
                raise ipc.FemmLinkError("FEMM 5 not found. Install it or set FEMM_DIR.")
            p = Path(path).resolve()
            if not p.is_file():
                raise ToolInputError(f"script not found: {p}", "Pass an existing .lua path.")
            port = ipc.pick_free_port(ipc.DEFAULT_PORT + 80)
            bat = inst.bin_dir / "femm-lua.bat"
            sh = inst.bin_dir / "femm-lua"
            opts = (["-h"] if headless else []) + ["-p", str(port), str(p)] + [str(a) for a in as_list(args)]
            if os.name == "nt" and bat.is_file():
                cmd = ["cmd", "/c", str(bat)] + opts
            elif sh.is_file():
                cmd = [str(sh)] + opts
            else:
                raise ToolInputError("femm-lua launcher not found in the FEMM bin folder",
                                     "This FEMM 5 build has no Lua 4 runner; port the script to MicroPython (femm_run_script).")
            t0 = time.time()
            try:
                r = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, cwd=str(p.parent))
            except subprocess.TimeoutExpired as e:
                raise ToolInputError(f"Lua script exceeded {timeout} s", "Increase timeout.") from e
            return {"script": p.as_posix(), "exit_code": r.returncode, "stdout": (r.stdout or "")[-20000:],
                    "stderr": (r.stderr or "")[-5000:], "seconds": round(time.time() - t0, 3)}
        return envelope(run)

    @mcp.tool()
    def femm_journal(limit: int = 200, save: bool = False, session: str = "main") -> dict:
        """The raw command lines this session sent to FEMM (most recent `limit`), i.e. exactly what
        the engine executed; commands FEMM refused are prefixed '#! ' with the error. save=True also writes the full journal as a replayable in-process
        script (<work_dir>/scripts/journal.py: run it with femm_run_script(path=...)).
        Internal pings are filtered out. Use femm_export_pyfemm_script for a standalone file."""
        def run(s: Session):
            lines = [ln for ln in s.link.journal if not _INTERNAL.match(ln.strip())]
            out: dict[str, Any] = {"total": len(lines), "lines": lines[-limit:] if limit else lines}
            if len(s.link.journal) >= s.link.journal_limit:
                out["truncated"] = f"journal is capped at {s.link.journal_limit} lines"
            if save:
                p = _scripts_dir(s) / "journal.py"
                p.write_text("# FEMM Agent Suite session journal (in-process MicroPython)\n" + "\n".join(lines) + "\n",
                             encoding="utf-8")
                out["file"] = p.as_posix()
            return out
        return run_tool(ctx, session, run)

    @mcp.tool()
    def femm_export_pyfemm_script(path: str | None = None, headless: bool = True, session: str = "main") -> dict:
        """Write the session journal as a standalone pyFEMM script (import femm; femm.openfemm(1);
        femm.mi_...(); femm.closefemm()) so the user can re-run the whole model without the agent.
        Default path: <work_dir>/scripts/<session>_pyfemm.py. femm_eval expressions that are not
        plain calls are kept as comments."""
        def run(s: Session):
            lines = [ln for ln in s.link.journal if not _INTERNAL.match(ln.strip())]
            inst = ctx.sessions.install
            text = journal_to_pyfemm(lines, headless, str(inst.bin_dir) if inst else None)
            p = Path(path) if path else _scripts_dir(s) / f"{s.name}_pyfemm.py"
            if not p.is_absolute():
                p = s.work_dir / p
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text, encoding="utf-8")
            return {"file": p.resolve().as_posix(), "calls": len(lines), "preview": text.splitlines()[:15]}
        return run_tool(ctx, session, run)
