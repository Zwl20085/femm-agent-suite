"""Generate per-sentence narration with Edge TTS and write src/audioConfig.ts.

Usage (from the repo root):
    .venv\Scripts\pip install edge-tts
    .venv\Scripts\python video\scripts\generate_audio_edge.py [--force]

Reads video/scripts/narration.json (a line is a string, or {"say", "show"} when the
caption should differ from the spoken words). Existing mp3 files are reused unless --force.
Durations are measured with ffprobe. If Edge TTS is unreachable, pass --captions-only
to write an audioConfig.ts with estimated timings and no audio files.
"""
from __future__ import annotations

import asyncio
import json
import subprocess
import sys
from pathlib import Path

FPS = 30
LEAD_IN = 0.6   # seconds before the first line of a scene
GAP = 0.35      # seconds between lines
TAIL = 0.9      # seconds after the last line

ROOT = Path(__file__).resolve().parent.parent
AUDIO_DIR = ROOT / "public" / "audio"
CONFIG = ROOT / "src" / "audioConfig.ts"


def duration(path: Path) -> float:
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(path)],
        capture_output=True, text=True, check=True,
    ).stdout.strip()
    return float(out)


async def synth(text: str, voice: str, rate: str, path: Path) -> None:
    import edge_tts

    await edge_tts.Communicate(text, voice, rate=rate).save(str(path))


def main() -> None:
    force = "--force" in sys.argv
    captions_only = "--captions-only" in sys.argv
    spec = json.loads((ROOT / "scripts" / "narration.json").read_text(encoding="utf-8"))
    AUDIO_DIR.mkdir(parents=True, exist_ok=True)
    scenes = []
    for si, scene in enumerate(spec["scenes"]):
        t = LEAD_IN
        lines = []
        for li, entry in enumerate(scene["lines"]):
            # a line is either a string or {"say": spoken text, "show": caption text}
            text = entry["say"] if isinstance(entry, dict) else entry
            shown = entry["show"] if isinstance(entry, dict) else entry
            name = f"{si + 1:02d}-{scene['id']}-{li + 1}.mp3"
            path = AUDIO_DIR / name
            if captions_only:
                d = max(1.2, len(text) / 15.0)
                name = ""
            else:
                if force or not path.exists():
                    print(f"  tts {name}", flush=True)
                    asyncio.run(synth(text, spec["voice"], spec.get("rate", "+0%"), path))
                d = duration(path)
            lines.append({"text": shown, "file": name, "from": round(t * FPS), "frames": round(d * FPS) + 1})
            t += d + GAP
        total = max(scene["minSeconds"], t - GAP + TAIL)
        scenes.append({"id": scene["id"], "title": scene["title"],
                       "durationInFrames": round(total * FPS), "lines": lines})
        print(f"{scene['id']:<14} {total:6.2f} s", flush=True)

    body = ",\n".join("  " + json.dumps(s, ensure_ascii=False) for s in scenes)
    CONFIG.write_text(
        "// Generated by scripts/generate_audio_edge.py - do not edit by hand.\n"
        "export type Line = { text: string; file: string; from: number; frames: number };\n"
        "export type SceneConfig = { id: string; title: string; durationInFrames: number; lines: Line[] };\n\n"
        f"export const FPS = {FPS};\n"
        f"export const HAS_AUDIO = {'false' if captions_only else 'true'};\n"
        "export const SCENES: SceneConfig[] = [\n" + body + "\n];\n\n"
        "export const getSceneStart = (index: number): number =>\n"
        "  SCENES.slice(0, index).reduce((sum, s) => sum + s.durationInFrames, 0);\n\n"
        "export const TOTAL_FRAMES = SCENES.reduce((sum, s) => sum + s.durationInFrames, 0);\n",
        encoding="utf-8",
    )
    total = sum(s["durationInFrames"] for s in scenes) / FPS
    print(f"total          {total:6.2f} s -> {CONFIG}")


if __name__ == "__main__":
    main()
